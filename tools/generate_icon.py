#!/usr/bin/env python3
"""
Draws Zaka's launcher icon and writes it as Android vector drawables.

The mark is a two-tone rand coin: a nickel ring with a milled edge and a brass
centre carrying an R. It is drawn here rather than exported from a design tool
for the reason the iOS icon is a script — vector art with no source is art
nobody can correct, and a committed PNG hides the only version that matters.

    python3 tools/generate_icon.py

Writes the drawables under app/src/main/res/ and a preview SVG under build/,
which is the thing to open when changing any of the numbers below.
"""

import math
import os

# --- the drawing, in the 108dp adaptive-icon canvas -------------------------
#
# Adaptive icons are 108x108dp and the launcher may crop to any shape inside
# that. Only the middle 72x72 is guaranteed to survive, so the coin is sized to
# sit inside it with room to spare: a 68dp coin, centred.

CANVAS = 108.0
CENTRE = CANVAS / 2
R_COIN = 34.0          # outer edge of the nickel ring
R_MILL = 30.5          # where the milling stops
R_BRASS = 23.0         # the brass centre
TEETH = 56             # milled flutes, as on a real R5

NICKEL = "#C3C9CF"
NICKEL_DARK = "#9AA2AA"
BRASS = "#C8922F"
BRASS_DARK = "#A8761F"
INK = "#4A3410"
BACKGROUND = "#FBF8F3"

# An R built from straight runs and three curves. Its own bounding box is
# centred on (58.75, 55) rather than on the canvas, so the transform below
# recentres it and shrinks it until it clears the brass rim. Keeping the glyph
# in its own coordinates and moving it with a transform means the path data
# never has to be hand-edited to nudge it.
R_BBOX_CENTRE = (58.75, 55.0)
R_SCALE = 0.86

# Second subpath is the counter, cut out with even-odd filling.
R_GLYPH = (
    "M45,39 H58 C66,39 70.5,43 70.5,48.5 C70.5,53 68,56.3 63.5,57.4 "
    "L72.5,71 H63 L55,58.4 H53.5 V71 H45 Z "
    "M53.5,45.5 V52.4 H57.8 C60.8,52.4 62.3,51 62.3,49 C62.3,47 60.8,45.5 57.8,45.5 Z"
)


def milled_edge(r_in: float, r_out: float, teeth: int) -> str:
    """The flutes around the rim, as one path of radial quadrilaterals."""
    parts = []
    for i in range(teeth):
        a0 = i * 2 * math.pi / teeth
        a1 = (i + 0.42) * 2 * math.pi / teeth
        corners = (
            (CENTRE + r_in * math.cos(a0), CENTRE + r_in * math.sin(a0)),
            (CENTRE + r_out * math.cos(a0), CENTRE + r_out * math.sin(a0)),
            (CENTRE + r_out * math.cos(a1), CENTRE + r_out * math.sin(a1)),
            (CENTRE + r_in * math.cos(a1), CENTRE + r_in * math.sin(a1)),
        )
        parts.append(
            "M%.2f,%.2f L%.2f,%.2f L%.2f,%.2f L%.2f,%.2f Z"
            % tuple(value for corner in corners for value in corner)
        )
    return " ".join(parts)


def circle(cx: float, cy: float, r: float) -> str:
    """A circle as path data, because vector drawables have no circle element."""
    return (
        "M%.2f,%.2f a%.2f,%.2f 0 1,0 %.2f,0 a%.2f,%.2f 0 1,0 -%.2f,0 Z"
        % (cx - r, cy, r, r, 2 * r, r, r, 2 * r)
    )


MILLING = milled_edge(R_MILL, R_COIN, TEETH)

FOREGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icon.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">

    <!-- the nickel ring -->
    <path android:fillColor="{NICKEL_DARK}" android:pathData="{circle(CENTRE, CENTRE, R_COIN)}" />
    <path android:fillColor="{NICKEL}" android:pathData="{circle(CENTRE, CENTRE, R_COIN - 1.4)}" />

    <!-- the milled edge -->
    <path android:fillColor="{NICKEL_DARK}" android:pathData="{MILLING}" />

    <!-- the brass centre -->
    <path android:fillColor="{BRASS_DARK}" android:pathData="{circle(CENTRE, CENTRE, R_BRASS)}" />
    <path android:fillColor="{BRASS}" android:pathData="{circle(CENTRE, CENTRE, R_BRASS - 1.2)}" />

    <!-- the R -->
    <group
        android:pivotX="{R_BBOX_CENTRE[0]}"
        android:pivotY="{R_BBOX_CENTRE[1]}"
        android:scaleX="{R_SCALE}"
        android:scaleY="{R_SCALE}"
        android:translateX="{CENTRE - R_BBOX_CENTRE[0]:.2f}"
        android:translateY="{CENTRE - R_BBOX_CENTRE[1]:.2f}">
        <path
            android:fillColor="{INK}"
            android:fillType="evenOdd"
            android:pathData="{R_GLYPH}" />
    </group>
</vector>
"""

BACKGROUND_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icon.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{BACKGROUND}" android:pathData="M0,0 H108 V108 H0 Z" />
</vector>
"""

# Themed icons are tinted by the launcher, so this layer is a silhouette: the
# ring and the R only, with the coin's two tones collapsed to one.
MONOCHROME = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icon.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#000000"
        android:fillType="evenOdd"
        android:pathData="{circle(CENTRE, CENTRE, R_COIN)} {circle(CENTRE, CENTRE, R_COIN - 4.5)}" />
    <path android:fillColor="#000000" android:pathData="{MILLING}" />
    <group
        android:pivotX="{R_BBOX_CENTRE[0]}"
        android:pivotY="{R_BBOX_CENTRE[1]}"
        android:scaleX="{R_SCALE}"
        android:scaleY="{R_SCALE}"
        android:translateX="{CENTRE - R_BBOX_CENTRE[0]:.2f}"
        android:translateY="{CENTRE - R_BBOX_CENTRE[1]:.2f}">
        <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{R_GLYPH}" />
    </group>
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icon.py. Edit the script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""

PREVIEW = f"""<!doctype html>
<html><head><meta charset="utf-8"><title>Zaka icon preview</title>
<style>
 body {{ margin:0; padding:24px; background:#E8E6E1;
        font:12px -apple-system,"Helvetica Neue",sans-serif; color:#444 }}
 .row {{ display:flex; gap:26px; align-items:flex-start; flex-wrap:wrap }}
 figure {{ margin:0; text-align:center }}
 figcaption {{ margin-top:7px; font-size:11px }}
 .circle svg {{ clip-path: circle(50% at 50% 50%) }}
 .squircle svg {{ clip-path: inset(0 round 24%) }}
 .frame {{ background:{BACKGROUND}; display:block }}
</style></head><body>
<div class="row">
  <figure><svg class="frame" width="180" height="180" viewBox="0 0 108 108">{{ART}}</svg>
    <figcaption>full 108dp canvas</figcaption></figure>
  <figure class="circle"><svg class="frame" width="140" height="140" viewBox="0 0 108 108">{{ART}}</svg>
    <figcaption>circle mask</figcaption></figure>
  <figure class="squircle"><svg class="frame" width="140" height="140" viewBox="0 0 108 108">{{ART}}</svg>
    <figcaption>squircle mask</figcaption></figure>
  <figure class="circle"><svg class="frame" width="60" height="60" viewBox="0 0 108 108">{{ART}}</svg>
    <figcaption>60px</figcaption></figure>
  <figure class="circle"><svg class="frame" width="42" height="42" viewBox="0 0 108 108">{{ART}}</svg>
    <figcaption>42px</figcaption></figure>
  <figure class="circle"><svg width="140" height="140" viewBox="0 0 108 108" style="background:#1D1B16">
      <g fill="#E8E2D9">{{MONO}}</g></svg>
    <figcaption>themed (monochrome)</figcaption></figure>
</div></body></html>
"""

R_SVG_TRANSFORM = (
    f"translate({CENTRE - R_BBOX_CENTRE[0]:.2f},{CENTRE - R_BBOX_CENTRE[1]:.2f}) "
    f"translate({R_BBOX_CENTRE[0]},{R_BBOX_CENTRE[1]}) scale({R_SCALE}) "
    f"translate(-{R_BBOX_CENTRE[0]},-{R_BBOX_CENTRE[1]})"
)

ART = (
    f'<path fill="{NICKEL_DARK}" d="{circle(CENTRE, CENTRE, R_COIN)}"/>'
    f'<path fill="{NICKEL}" d="{circle(CENTRE, CENTRE, R_COIN - 1.4)}"/>'
    f'<path fill="{NICKEL_DARK}" d="{MILLING}"/>'
    f'<path fill="{BRASS_DARK}" d="{circle(CENTRE, CENTRE, R_BRASS)}"/>'
    f'<path fill="{BRASS}" d="{circle(CENTRE, CENTRE, R_BRASS - 1.2)}"/>'
    f'<g transform="{R_SVG_TRANSFORM}">'
    f'<path fill="{INK}" fill-rule="evenodd" d="{R_GLYPH}"/></g>'
)

MONO_ART = (
    f'<path fill-rule="evenodd" d="{circle(CENTRE, CENTRE, R_COIN)} '
    f'{circle(CENTRE, CENTRE, R_COIN - 4.5)}"/>'
    f'<path d="{MILLING}"/>'
    f'<g transform="{R_SVG_TRANSFORM}">'
    f'<path fill-rule="evenodd" d="{R_GLYPH}"/></g>'
)


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as handle:
        handle.write(text)
    print(f"  {path}")


def main() -> None:
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir)
    res = os.path.join(root, "app", "src", "main", "res")

    print("Generating the launcher icon:")
    write(os.path.join(res, "drawable", "ic_launcher_foreground.xml"), FOREGROUND)
    write(os.path.join(res, "drawable", "ic_launcher_background.xml"), BACKGROUND_XML)
    write(os.path.join(res, "drawable", "ic_launcher_monochrome.xml"), MONOCHROME)
    write(os.path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE)
    write(os.path.join(res, "mipmap-anydpi-v26", "ic_launcher_round.xml"), ADAPTIVE)
    write(
        os.path.join(root, "build", "icon-preview.html"),
        PREVIEW.replace("{ART}", ART).replace("{MONO}", MONO_ART),
    )


if __name__ == "__main__":
    main()
